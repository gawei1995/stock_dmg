test("golden native USD quantity and two broker FX conversions are applied exactly once", () => {
  const longbridge = portfolioFixture();
  const ibkr = normalizeIbkrPortfolio(ibkrInput());
  assert.equal(longbridge.account.baseCurrency, "USD");
  assert.equal(longbridge.account.netAssets, 10000); // HKD 80,000 / 8
  assert.equal(longbridge.positions[0].quantity, 2);
  assert.equal(longbridge.positions[0].currency, "USD");
  assert.equal(longbridge.positions[0].marketValue, 500); // 2 shares * USD 250
  assert.equal(longbridge.positions[0].marketValueBase, 500);
  assert.equal(longbridge.positions[0].weight, 5); // percent, not ratio .05
  assert.equal(ibkr.account.netAssets, 5000); // HKD 40,000 / 8
  assert.equal(ibkr.positions[0].marketValueBase, 1000);
  const all = buildBrokerViews({ longbridge, ibkr, ibkrEnabled: true, now: Date.parse(EVAL.at) }).all;
  assert.equal(all.account.netAssets, 15000);
  assert.equal(all.positions[0].quantity, 6);
  assert.equal(all.positions[0].marketValueBase, 1500);
  assert.equal(all.account.buyPower, null); // cross-account buying power is not additive
  const pack = coreFor(all);
  const fact = factFor(pack, "portfolio.net_assets");
  const golden = { value: "15000", unit: { kind: "money", currency: "USD" }, availability: "known",
    effectiveAt: EVAL.at, session: "not_applicable", complete: true, reasonCodes: [] };
  assertGolden(fact, golden);
  const claim = literalCitation(fact, golden);
  assert.deepEqual(syntheticCitationAudit(pack.facts, claim), []);
  assert.deepEqual(syntheticCitationAudit(pack.facts, { ...claim, value: "1875" }), ["value_mismatch"]); // double FX
  assert.deepEqual(syntheticCitationAudit(pack.facts, { ...claim, unit: { kind: "money", currency: "HKD" } }), ["unit_mismatch"]);
  assert.deepEqual(syntheticCitationAudit(pack.facts, { ...claim, unit: { kind: "quantity", quantityType: "shares" } }), ["unit_mismatch"]);
});

