// This is deliberately NOT a production semantic auditor or a prose/model eval.
// It compares synthetic structured citations against host-generated facts after
// independent literal goldens have passed. It cannot claim to detect bad prose.
function syntheticCitationAudit(facts, claim, { cutoffAt = null } = {}) {
  const fact = facts.find((item) => item.factId === claim.factId);
  if (!fact) return ["missing_fact"];
  try { validateNumericEvidence(fact); } catch { return ["invalid_fact"]; }
  const issues = [];
  if (claim.hash !== fact.hash) issues.push("hash_mismatch");
  for (const field of ["value", "unit", "availability"]) {
    if (!isDeepStrictEqual(claim[field], fact[field])) issues.push(`${field}_mismatch`);
  }
  if (claim.effectiveAt !== fact.asOf.effectiveAt) issues.push("effective_time_mismatch");
  if (claim.session !== fact.asOf.session) issues.push("session_mismatch");
  if (claim.complete !== fact.quality.complete) issues.push("completeness_mismatch");
  if (claim.reasonCodes && !isDeepStrictEqual(claim.reasonCodes, fact.quality.reasonCodes)) issues.push("qualification_mismatch");
  if (cutoffAt && Date.parse(fact.asOf.effectiveAt) > Date.parse(cutoffAt)) issues.push("after_cutoff");
  return issues;
}

function portfolioFixture(options) {
  const result = normalizePortfolio(longbridgeInput(options));
  // Supply a deterministic transport observation time; numeric values are all
  // generated by the real normalizer, not independently manufactured facts.
  result.syncedAt = EVAL.at;
  return result;
}
function coreFor(portfolio, extra = {}) {
  return buildCoreNumericEvidence({ portfolio, risk: calculatePortfolioRisk(portfolio, 0.8),
    now: () => new Date(EVAL.at), ...extra });
}
function factFor(pack, metric) {
  const fact = pack.facts.find((row) => row.metric === metric);
  assert.ok(fact, `host fact must exist: ${metric}`);
  validateNumericEvidence(fact);
  return fact;
}
function literalCitation(fact, golden) {
  // Only the reference comes from the generated fact. Values/units/time below
  // come from fixed literal expected answers, not from the fact under test.
  return { factId: fact.factId, hash: fact.hash, ...golden };
}
function assertGolden(fact, golden) {
  for (const field of ["value", "unit", "availability"]) assert.deepEqual(fact[field], golden[field]);
  assert.equal(fact.asOf.effectiveAt, golden.effectiveAt);
  assert.equal(fact.asOf.session, golden.session);
  assert.equal(fact.quality.complete, golden.complete);
  if (golden.reasonCodes) assert.deepEqual(fact.quality.reasonCodes, golden.reasonCodes);
}
function proposalAudit({ unit = { kind: "percent_point", basis: "portfolio_net_assets" }, factValue = 4, claimedValue = 4, at = EVAL.at } = {}) {
  const pack = coreFor(portfolioFixture());
  const fact = createModelProposal({
    factId: `eval-proposal@${at}`, metric: "candidate.sizing.model_initial_additional_weight_percent",
    value: factValue, availability: "known", unit,
    asOf: { effectiveAt: at, retrievedAt: at, tradingDate: null, session: "not_applicable", timeZone: "UTC" },
    provenance: { source: "synthetic model citation", tool: "test:offline", sourceRecordId: null, rawFields: [],
      inputRefs: [numericEvidenceRef(factFor(pack, "portfolio.net_assets"))], formula: null, methodVersion: EVAL.version },
    quality: { freshness: "fresh", ageMs: 0, complete: true, confidence: "medium", reasonCodes: [] },
    display: { precision: 2, label: "Synthetic proposed weight" },
  });
  return auditCandidateSizingClaims({ numericEvidence: { ...pack, facts: [...pack.facts, fact],
    sizingDecision: { decisionAt: EVAL.at, proposalFactIds: [fact.factId], hostDecisionFactIds: [], derivedMetricFactIds: [] } },
  sizingReview: { decisionAt: EVAL.at, modelProposal: { initialAdditionalWeightPercent: claimedValue }, accepted: {} }, entryAllowed: false });
}

