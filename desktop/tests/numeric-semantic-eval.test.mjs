test("zero buying power is a known zero; absent buying power remains unknown, never inferred zero", () => {
  const portfolio = portfolioFixture();
  const knownPack = coreFor(portfolio);
  const known = factFor(knownPack, "portfolio.buy_power");
  const golden = { value: "0", unit: { kind: "money", currency: "USD" }, availability: "known",
    effectiveAt: EVAL.at, session: "not_applicable", complete: true, reasonCodes: [] };
  assertGolden(known, golden);
  portfolio.account.buyPower = null;
  const pack = coreFor(portfolio);
  const unknown = factFor(pack, "portfolio.buy_power");
  assert.equal(unknown.value, null);
  assert.equal(unknown.availability, "unknown");
  assert.equal(unknown.quality.complete, false);
  assert.ok(unknown.quality.reasonCodes.length > 0);
  assert.notEqual(unknown.hash, known.hash);
  assert.deepEqual(unknown.quality.reasonCodes, ["source_value_missing"]);
  const claim = literalCitation(unknown, { ...golden, value: null, availability: "unknown", complete: false,
    reasonCodes: ["source_value_missing"] });
  assert.deepEqual(syntheticCitationAudit(pack.facts, claim), []);
  assert.deepEqual(syntheticCitationAudit(pack.facts, { ...claim, value: "0", availability: "known", complete: true }),
    ["value_mismatch", "availability_mismatch", "completeness_mismatch"]);
});

test("option premium applies the explicit multiplier once and never becomes Delta exposure", () => {
  const portfolio = portfolioFixture({ option: true });
  const option = portfolio.positions[0];
  assert.equal(option.quantity, 2);
  assert.equal(option.contractMultiplier, 100);
  assert.equal(option.lastPrice, 5);
  assert.equal(option.marketValueBase, 1000);
  const risk = calculatePortfolioRisk(portfolio);
  assert.equal(risk.grossExposurePercent, 10);
  assert.equal(risk.derivativeExposureComplete, false);
  assert.match(risk.derivativeExposureLimitation, /Delta.*权利金市值不能替代/);
  const pack = coreFor(portfolio);
  assert.equal(pack.status, "partial");
  assert.equal(pack.facts.some((fact) => fact.metric === "portfolio.positions_gross_notional"), false);
  const premiumValue = factFor(pack, "portfolio.positions_gross_market_value");
  const reasons = ["derivative_risk_exposure_incomplete", "includes_option_premium_market_value", "not_delta_or_underlying_notional_exposure"];
  const golden = { value: "1000", unit: { kind: "money", currency: "USD" }, availability: "known",
    effectiveAt: EVAL.at, session: "not_applicable", complete: false, reasonCodes: reasons };
  assertGolden(premiumValue, golden);
  assert.match(premiumValue.display.label, /权利金.*非 Delta/);
  const exposure = factFor(pack, "portfolio.gross_exposure_percent");
  assert.equal(exposure.value, "10");
  assert.equal(exposure.quality.complete, false);
  assert.deepEqual(exposure.quality.reasonCodes, reasons);
  const claim = literalCitation(premiumValue, golden);
  assert.deepEqual(syntheticCitationAudit(pack.facts, claim), []);
  assert.deepEqual(syntheticCitationAudit(pack.facts, { ...claim, complete: true, reasonCodes: [] }),
    ["completeness_mismatch", "qualification_mismatch"]);
  const missing = portfolioFixture({ option: true, multiplier: null });
  assert.equal(missing.positions[0].contractMultiplier, null);
  assert.equal(missing.positions[0].marketValueBase, null);
  assert.equal(missing.dataQuality.valuationComplete, false);
});

