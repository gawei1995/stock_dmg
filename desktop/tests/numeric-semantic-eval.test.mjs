test("production candidate auditor rejects ratio/percent confusion, changed values and stale decisions", () => {
  const accepted = proposalAudit();
  assert.equal(accepted.status, "verified");
  assert.equal(accepted.claimIndex[0].value, "4");
  assert.equal(accepted.claimIndex[0].unit, "percent_point");
  assert.equal(accepted.executionAuthorized, false); // proposal never becomes host authority
  for (const [options, code] of [
    [{ unit: { kind: "ratio", basis: "portfolio_net_assets" }, factValue: 0.04 }, "claim_unit_mismatch"],
    [{ claimedValue: 0.04 }, "claim_value_mismatch"],
    [{ at: "2026-08-30T21:01:00.000Z" }, "claim_decision_time_mismatch"],
  ]) {
    const result = proposalAudit(options);
    assert.equal(result.status, "failed");
    assert.ok(result.issues.some((issue) => issue.code === code));
  }
});

